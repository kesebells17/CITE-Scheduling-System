<?php
// reports/generate_pdf.php
// Core PDF Generation logic using FPDF

// Load FPDF - We assume it's in php/libs/
if (file_exists('../php/libs/fpdf/fpdf.php')) {
    require_once('../php/libs/fpdf/fpdf.php');
} else if (file_exists('fpdf/fpdf.php')) {
    require_once('fpdf/fpdf.php');
} else {
    die("FPDF Library not found. Please place fpdf library in reports/fpdf/ or php/libs/fpdf/");
}

class CITE_Report extends FPDF {
    protected $generated_by = "System";
    protected $report_title = "Consultation Report";

    function setGeneratedBy($name) { $this->generated_by = $name; }
    function setReportTitle($title) { $this->report_title = $title; }

    function Header() {
        // Logo
        if (file_exists('../images/citelogo.png')) {
            $this->Image('../images/citelogo.png', 10, 10, 25);
        }
        
        // Header Text
        $this->SetFont('Arial', 'B', 14);
        $this->Cell(30); // Spacer
        $this->Cell(0, 10, 'FACULTY & STAFF CONSULTATION MONITORING SYSTEM', 0, 1, 'L');
        
        $this->SetFont('Arial', '', 12);
        $this->Cell(30);
        $this->Cell(0, 8, 'CITE / PHINMA COC', 0, 1, 'L');
        
        $this->SetFont('Arial', '', 10);
        $this->Cell(30);
        $this->Cell(0, 5, 'Max Y. Suniel St, Cagayan de Oro, 9000 Misamis Oriental', 0, 1, 'L');
        $this->Cell(30);
        $this->Cell(0, 5, 'Email: cite.coc@phinmaed.com', 0, 1, 'L');
        
        $this->Ln(10);
        $this->SetDrawColor(0, 100, 0); // Dark Green
        $this->SetLineWidth(1);
        $this->Line(10, 45, 200, 45);
        $this->Ln(5);

        // Generated By & Date
        $this->SetFont('Arial', 'I', 9);
        $this->Cell(0, 10, 'Generated on: ' . date('F d, Y') . ' | Generated by: ' . $this->generated_by, 0, 1, 'R');
        $this->Ln(5);
    }

    function Footer() {
        $this->SetY(-15);
        $this->SetFont('Arial', 'I', 8);
        $this->Cell(0, 10, 'Page ' . $this->PageNo() . ' | CITE Faculty & Staff Consultation Monitoring System', 0, 0, 'C');
    }

    function SectionTitle($title) {
        $this->SetFont('Arial', 'B', 12);
        $this->SetFillColor(230, 230, 230);
        $this->Cell(0, 10, "  " . strtoupper($title), 0, 1, 'L', true);
        $this->Ln(3);
    }

    function ProfileSection($data) {
        $this->SetFont('Arial', 'B', 11);
        
        // Profile Picture
        $pic = '../uploadsInstructorProfilePic/default_avatar.png';
        if (!empty($data['profile_picture'])) {
            $path = '../uploadsInstructorProfilePic/' . $data['profile_picture'];
            if (file_exists($path)) {
                $pic = $path;
            }
        }
        
        // Draw square frame for picture
        $this->Image($pic, 10, $this->GetY(), 30, 30);
        
        $this->SetX(45);
        $this->Cell(40, 7, 'Full Name:', 0, 0);
        $this->SetFont('Arial', '', 11);
        $this->Cell(0, 7, $data['name'], 0, 1);
        
        $this->SetX(45);
        $this->SetFont('Arial', 'B', 11);
        $this->Cell(40, 7, 'Employee ID:', 0, 0);
        $this->SetFont('Arial', '', 11);
        $this->Cell(0, 7, $data['employee_id'] ?? 'N/A', 0, 1);
        
        $this->SetX(45);
        $this->SetFont('Arial', 'B', 11);
        $this->Cell(40, 7, 'Department:', 0, 0);
        $this->SetFont('Arial', '', 11);
        $this->Cell(0, 7, $data['department'] ?? 'N/A', 0, 1);
        
        $this->SetX(45);
        $this->SetFont('Arial', 'B', 11);
        $this->Cell(40, 7, 'Position:', 0, 0);
        $this->SetFont('Arial', '', 11);
        $this->Cell(0, 7, $data['position'] ?? 'Faculty Specialist', 0, 1);

        $this->Ln(10);
    }

    function SummaryBox($stats) {
        $this->SetFont('Arial', 'B', 10);
        $this->SetFillColor(245, 255, 250); // Mint color
        $this->Rect(10, $this->GetY(), 190, 45, 'F');
        
        $this->SetX(15);
        $this->Cell(60, 8, 'Total Hours Rendered:', 0, 0);
        $this->Cell(30, 8, round($stats['rendered_hours'], 2) . ' hrs', 0, 0);
        $this->Cell(60, 8, 'Face-to-Face Count:', 0, 0);
        $this->Cell(0, 8, $stats['f2f_count'], 0, 1);

        $this->SetX(15);
        $this->Cell(60, 8, 'Required Weekly Hours:', 0, 0);
        $this->Cell(30, 8, '10 hrs', 0, 0);
        $this->Cell(60, 8, 'Online Count:', 0, 0);
        $this->Cell(0, 8, $stats['online_count'], 0, 1);

        $this->SetX(15);
        $this->Cell(60, 8, 'Remaining / Balance:', 0, 0);
        $this->Cell(30, 8, max(0, 10 - $stats['rendered_hours']) . ' hrs', 0, 0);
        $this->Cell(60, 8, 'Total Completed:', 0, 0);
        $this->Cell(0, 8, $stats['completed_count'], 0, 1);

        $this->SetX(15);
        $this->Cell(60, 8, 'Overtime Hours:', 0, 0);
        $this->Cell(30, 8, max(0, $stats['rendered_hours'] - 10) . ' hrs', 0, 0);
        $this->Cell(60, 8, 'Total Follow-Ups:', 0, 0);
        $this->Cell(0, 8, $stats['followup_count'], 0, 1);

        $this->Ln(5);
        
        // Status Badge
        $status = "BELOW REQUIREMENT";
        $color = [200, 0, 0]; // Red
        if ($stats['rendered_hours'] >= 10) {
            $status = "COMPLETED REQUIREMENT";
            $color = [0, 128, 0]; // Green
        }
        if ($stats['rendered_hours'] > 12) {
            $status = "EXCEEDED REQUIREMENT";
            $color = [0, 0, 200]; // Blue
        }

        $this->SetX(15);
        $this->SetTextColor($color[0], $color[1], $color[2]);
        $this->SetFont('Arial', 'B', 12);
        $this->Cell(0, 10, "STATUS: $status", 0, 1);
        $this->SetTextColor(0, 0, 0);
        $this->Ln(5);
    }

    function ConsultationTable($records) {
        $this->SetFont('Arial', 'B', 9);
        $this->SetFillColor(6, 95, 70); // Theme Green
        $this->SetTextColor(255, 255, 255);
        
        $this->Cell(20, 8, 'Date', 1, 0, 'C', true);
        $this->Cell(45, 8, 'Student', 1, 0, 'C', true);
        $this->Cell(25, 8, 'Type', 1, 0, 'C', true);
        $this->Cell(20, 8, 'Duration', 1, 0, 'C', true);
        $this->Cell(30, 8, 'Outcome', 1, 0, 'C', true);
        $this->Cell(50, 8, 'Short Summary', 1, 1, 'C', true);
        
        $this->SetTextColor(0, 0, 0);
        $this->SetFont('Arial', '', 8);
        
        if (count($records) == 0) {
            $this->Cell(190, 8, 'No records found for this period', 1, 1, 'C');
            return;
        }

        foreach ($records as $r) {
            $h = 8; // Row height
            // Calculate height for summary multi-cell
            $summary = substr($r['summary_of_discussion'], 0, 100);
            
            $this->Cell(20, $h, $r['date'], 1, 0, 'C');
            $this->Cell(45, $h, $r['student_name'], 1, 0, 'L');
            $this->Cell(25, $h, $r['consultation_type'], 1, 0, 'C');
            $this->Cell(20, $h, $r['duration_minutes'] . 'm', 1, 0, 'C');
            $this->Cell(30, $h, $r['outcome_status'], 1, 0, 'C');
            
            // Multiline cell for summary
            $x = $this->GetX();
            $y = $this->GetY();
            $this->MultiCell(50, 4, $summary, 1, 'L');
            $this->SetXY($x + 50, $y);
            $this->Ln($h);
        }
    }
}
